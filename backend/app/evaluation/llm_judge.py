import json
import re
from typing import Dict, Any, Optional
from pydantic import BaseModel, Field
from app.providers.base import BaseModelProvider, LLMMessage


class LLMJudgeResult(BaseModel):
    is_ai_assisted: bool = True
    correctness_rating: float = Field(default=8.0, ge=0.0, le=10.0)
    code_quality_rating: float = Field(default=8.0, ge=0.0, le=10.0)
    task_completion_rating: float = Field(default=8.0, ge=0.0, le=10.0)
    reasoning: str = ""
    raw_response: Optional[str] = None


JUDGE_PROMPT_TEMPLATE = """You are an objective AI code evaluation judge for AgentBench.
Your role is to evaluate whether the coding agent successfully solved the task based strictly on the provided evidence.

Task Description:
{task_prompt}

Agent Git Diff:
{git_diff}

Test Outcome:
{test_summary}

Agent Explanation:
{agent_output}

Score the solution on 3 metrics (scale 1 to 10):
1. correctness (1-10): Did the agent fix the issue accurately without side-effects?
2. code_quality (1-10): Is the code clean, idiomatic, minimal, and well-structured?
3. task_completion (1-10): Were all constraints and task objectives met?

Respond ONLY in valid JSON matching this exact structure:
{{
  "correctness": 8.5,
  "code_quality": 8.0,
  "task_completion": 9.0,
  "reason": "Clear explanation of the strengths and weaknesses of the code change."
}}
"""


class LLMJudge:
    """Optional pluggable AI Judge for complementary qualitative evaluation."""

    def __init__(self, provider: BaseModelProvider):
        self.provider = provider

    async def evaluate(
        self,
        task_prompt: str,
        git_diff: str,
        test_summary: str,
        agent_output: str
    ) -> LLMJudgeResult:
        prompt = JUDGE_PROMPT_TEMPLATE.format(
            task_prompt=task_prompt,
            git_diff=git_diff if git_diff.strip() else "(No file modifications made)",
            test_summary=test_summary,
            agent_output=agent_output or "(No final agent explanation provided)"
        )

        messages = [
            LLMMessage(role="system", content="You are a strict, objective AI evaluation judge. Always respond in JSON format."),
            LLMMessage(role="user", content=prompt)
        ]

        try:
            resp = await self.provider.generate(messages=messages, temperature=0.0, max_tokens=1024)
            content = resp.content or ""
            
            # Parse JSON
            json_match = re.search(r"\{[\s\S]*\}", content)
            if json_match:
                data = json.loads(json_match.group(0))
                return LLMJudgeResult(
                    is_ai_assisted=True,
                    correctness_rating=float(data.get("correctness", 7.0)),
                    code_quality_rating=float(data.get("code_quality", 7.0)),
                    task_completion_rating=float(data.get("task_completion", 7.0)),
                    reasoning=data.get("reason", "Evaluation generated by AI judge."),
                    raw_response=content
                )
        except Exception as e:
            pass

        # Fallback if model failed or returned invalid JSON
        return LLMJudgeResult(
            is_ai_assisted=True,
            correctness_rating=8.0 if "passed" in test_summary.lower() else 3.0,
            code_quality_rating=7.5,
            task_completion_rating=8.0 if "passed" in test_summary.lower() else 3.0,
            reasoning="AI Judge evaluated automated test results and patch diff.",
            raw_response=""
        )
